import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createServer } from 'vite'

const require = createRequire(new URL('../../../api/package.json', import.meta.url))
const { chromium } = require('playwright-core')
const frontendRequire = createRequire(new URL('../../../frontend/package.json', import.meta.url))
const { default: vueJsx } = await import(pathToFileURL(frontendRequire.resolve('@vitejs/plugin-vue-jsx')).href)
const { transform } = frontendRequire('esbuild')
const server = await createServer({
	server: { host: '127.0.0.1', port: 0, watch: null, hmr: false },
	resolve: { alias: [
		{ find: '@enlearn/lowcode-framework/components/low-code-form', replacement: fileURLToPath(new URL('../../lowcode-framework/src/components/LowCodeForm.vue', import.meta.url)) },
		{ find: 'tldraw-vue-phase-one/style.css', replacement: fileURLToPath(new URL('../src/styles.css', import.meta.url)) },
		{ find: 'tldraw-vue-phase-one', replacement: fileURLToPath(new URL('../src/index.ts', import.meta.url)) },
	] },
	plugins: [vueJsx({ include: /lowcode-framework\/.*\.tsx$/ }), {
		name: 'formula-test-react-tsx', enforce: 'pre', async transform(code, id) {
			if (id.replaceAll('\\', '/').includes('/tldraw-vue/') && id.endsWith('.tsx')) {
				return transform(code, { loader: 'tsx', jsx: 'automatic', jsxImportSource: 'react', target: 'esnext', tsconfigRaw: { compilerOptions: { experimentalDecorators: true } } })
			}
		},
	}, { name: 'formula-test-page', configureServer(server) {
		server.middlewares.use('/__formula-test', (_request, response) => {
			response.setHeader('Content-Type', 'text/html')
			response.end('<link rel="icon" href="data:,"><div id="editor" style="position:absolute;left:620px;width:800px;height:600px"></div><div id="panel" style="width:360px"></div><script type="module" src="/tests/print-formula-browser.ts"></script>')
		})
		server.middlewares.use('/__header-row-test', (_request, response) => {
			response.setHeader('Content-Type', 'text/html')
			response.end('<link rel="icon" href="data:,"><div id="editor" style="position:absolute;left:1000px;width:200px;height:600px"></div><div id="panel" style="width:600px;height:800px"></div><script type="module" src="/tests/print-header-row-browser.ts"></script>')
		})
	} }],
})
let browser
let page
try {
	await server.listen()
	browser = await chromium.launch({ headless: true, ...(process.env.PRINT_TEST_BROWSER ? { executablePath: process.env.PRINT_TEST_BROWSER } : { channel: 'msedge' }) })
	page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
	const errors = []
	page.on('pageerror', error => { errors.push(error.message); console.error(error.message) })
	page.on('console', message => { if (message.type() === 'error') console.error(message.text()) })
	page.on('requestfailed', request => console.error(request.url(), request.failure()?.errorText))
	await page.goto(`${server.resolvedUrls.local[0]}__formula-test`)
	await page.getByRole('button', { name: '插入公式', exact: true }).click({ timeout: 60_000 })
	const dialog = page.locator('.lowcode-confirm-form-dialog')
	const control = label => dialog.locator('.lc-field').nth({ '函数': 0, '明细源': 1, '字段': 2, '统计范围': 3, '小数位': 4, '示例页': 5, '生成公式': 6, '示例结果': 7 }[label]).locator('input,select')
	const preview = control('示例结果')
	const waitPreview = value => page.waitForFunction(value => [...document.querySelectorAll('.lc-field input')].at(-1)?.value === value, value)
	await waitPreview('100.00')
	await control('统计范围').selectOption('page')
	await control('示例页').selectOption('1')
	await waitPreview('20.00')
	await control('函数').selectOption('AVERAGE')
	await control('统计范围').selectOption('all')
	await waitPreview('25.00')
	await control('函数').selectOption('COUNT')
	assert.equal(await control('字段').isDisabled(), true)
	await waitPreview('4.00')
	await control('函数').selectOption('TOTAL')
	await page.getByRole('button', { name: '插入到文本末尾' }).click()
	await page.waitForFunction(() => !document.querySelector('.lowcode-confirm-form-dialog'))
	assert.equal(await page.evaluate(() => window.formulaTest.getText()), '金额合计：{{TOTAL(items.amount) | fixed:2}}')
	const rendered = await page.evaluate(() => window.formulaTest.render())
	assert.equal(rendered.count, 4)
	assert.deepEqual(rendered.captures, Array(4).fill('金额合计：100.00'))
	assert.equal(rendered.images, true)
	assert.equal(rendered.restored, true)
	await page.evaluate(() => window.formulaTest.undo())
	assert.equal(await page.evaluate(() => window.formulaTest.getText()), '金额合计：')
	const pages = await page.evaluate(() => window.formulaTest.componentPagination())
	assert.ok(pages.length > 1, JSON.stringify(pages))
	assert.ok(pages.every(page => page.total === '100'))
	assert.equal(pages.reduce((sum, page) => sum + Number(page.subtotal), 0), 100)
	assert.equal(pages.reduce((sum, page) => sum + page.count, 0), 4)
	await page.getByRole('button', { name: '插入公式', exact: true }).click()
	await control('统计范围').selectOption('page')
	await control('示例页').selectOption('1')
	assert.equal(await preview.inputValue(), Number(pages[1].subtotal).toFixed(2))
	await page.screenshot({ path: fileURLToPath(new URL('../../../artifacts/print-formula-local-preview.png', import.meta.url)), fullPage: true })
	await page.setViewportSize({ width: 375, height: 812 })
	const mobile = await dialog.locator('.vxe-modal--box').boundingBox()
	assert.ok(mobile.x >= 0 && mobile.x + mobile.width <= 375, JSON.stringify(mobile))
	assert.equal(await page.getByRole('button', { name: '插入到文本末尾' }).isVisible(), true)
	await page.getByRole('button', { name: '取消', exact: true }).click()
	await page.evaluate(() => window.formulaTest.setReadonly(true))
	assert.equal(await page.getByRole('button', { name: '插入公式', exact: true }).isDisabled(), true)
	await page.evaluate(() => window.formulaTest.setReadonly(false))
	const footer = await page.evaluate(() => window.formulaTest.materialFooterPagination())
	assert.deepEqual(footer.plan.map(page => page.rows), [2, 2, 1])
	assert.equal(footer.captures.length, footer.plan.length)
	for (const [index, capture] of footer.captures.entries()) {
		const height = footer.plan[index].height
		const removed = footer.original.bodyHeight - height
		assert.equal(capture.bodyHeight, height)
		assert.equal(capture.footerY, footer.bodyY + height, 'Table footer must touch the last actual row')
		assert.equal(capture.frameY, footer.original.frameY - removed, 'Nested frame must move with the footer')
		assert.equal(capture.labelY, footer.original.labelY - removed, 'Locked nested text must move with the footer')
		assert.equal(capture.footerHeight, footer.original.footerHeight)
		assert.equal(capture.frameHeight, footer.original.frameHeight)
		assert.equal(capture.labelHeight, footer.original.labelHeight)
		assert.equal(capture.pageFooterY, footer.original.pageFooterY, 'Page footer stays anchored')
		assert.equal(capture.pageFooterHeight, footer.original.pageFooterHeight)
		assert.equal(capture.text, ['本页合计：30', '本页合计：70', '本页合计：50'][index])
	}
	assert.equal(footer.images, true)
	assert.equal(footer.restored, true)
	assert.equal(footer.failed, true)
	assert.equal(footer.failureRestored, true)
	assert.equal(footer.emptyHeight, 30, 'Empty table must retain only its column header')
	assert.equal(footer.exactHeight, footer.exactBodyHeight)
	await page.evaluate(() => window.formulaTest.dispose())
	await page.setViewportSize({ width: 1400, height: 1000 })
	await page.goto(`${server.resolvedUrls.local[0]}__header-row-test`)
	await page.locator('.print-header-table').waitFor({ timeout: 60_000 })
	await page.locator('.print-header-table [data-lc-field="records"] .lc-array-table').waitFor()
	const originalRows = await page.evaluate(() => window.headerRowTest.rows())
	const rowDialog = page.locator('.print-header-row-dialog')
	const headerAction = (index, name) => page.locator('.print-header-table .vxe-table--fixed-right-wrapper .vxe-body--row').nth(index).getByRole('button', { name, exact: true })
	await headerAction(1, '复制').click()
	const copiedRows = await page.evaluate(() => window.headerRowTest.rows())
	assert.equal(copiedRows.length, 3)
	assert.deepEqual(copiedRows[2], originalRows[1], 'Copy must preserve legacy header, unknown fields and nested detail arrays')
	await headerAction(2, '删除').click()
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.rows()), originalRows)
	await page.locator('.print-header-table .lc-array-table__toolbar').getByRole('button', { name: '新增行', exact: true }).click()
	await rowDialog.locator('[data-lc-field="code"] input').waitFor()
	await rowDialog.getByRole('button', { name: '取消', exact: true }).click()
	await rowDialog.waitFor({ state: 'detached' })
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.rows()), originalRows)
	await page.evaluate(() => window.headerRowTest.setReadonly(true))
	assert.equal(await headerAction(1, '编辑').isDisabled(), true)
	assert.equal(await headerAction(1, '复制').isDisabled(), true)
	assert.equal(await headerAction(1, '删除').isDisabled(), true)
	assert.equal(await page.locator('.print-header-table').getByRole('button', { name: '新增行', exact: true }).isDisabled(), true)
	await page.locator('.print-header-table .vxe-table--main-wrapper .vxe-body--row').nth(1).getByText('B', { exact: true }).click()
	assert.equal(await page.evaluate(() => window.headerRowTest.selectedRow()), 1, 'Readonly must still allow switching the displayed record')
	await page.evaluate(() => window.headerRowTest.setReadonly(false))
	const editSecond = async () => {
		await headerAction(1, '编辑').click()
		await rowDialog.locator('[data-lc-field="code"] input').waitFor()
		assert.equal(await rowDialog.locator('[data-lc-field="code"] input').inputValue(), 'B')
	}
	const detail = field => rowDialog.locator(`[data-lc-field="${field}"]`)
	await editSecond()
	await page.evaluate(() => window.headerRowTest.deferFetch(true))
	await detail('items').getByRole('button', { name: '获取数据', exact: true }).click()
	await page.waitForFunction(() => window.headerRowTest.fetches().at(-1).params.code === 'B')
	assert.equal(await rowDialog.getByRole('button', { name: '保存', exact: true }).isDisabled(), true)
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.rows()), originalRows)
	await page.evaluate(() => { window.headerRowTest.deferFetch(false); window.headerRowTest.releaseFetch() })
	await page.waitForFunction(() => !document.querySelector('.print-header-row-dialog .lc-global-dialog__footer button[disabled]'))
	assert.equal(await rowDialog.locator('[data-lc-field="code"] input').inputValue(), 'B')
	assert.equal(await page.locator('.print-header-table').isVisible(), true)
	await detail('items').getByRole('button', { name: '同步字段', exact: true }).click()
	await detail('items').getByText('标记', { exact: true }).waitFor()
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.saves()), [])
	await rowDialog.getByRole('button', { name: '保存', exact: true }).click()
	await rowDialog.waitFor({ state: 'detached' })
	const savedRows = await page.evaluate(() => window.headerRowTest.rows())
	assert.deepEqual(savedRows[0], originalRows[0], 'Fetching the second record must not change the first record')
	assert.equal(savedRows[1].items[0].amount, 220)
	assert.equal(savedRows[1].items[0].tag, 'B-items')
	assert.deepEqual(savedRows[1].notes, originalRows[1].notes)
	assert.deepEqual(savedRows[1].extra, originalRows[1].extra)
	assert.deepEqual(savedRows[1].header, originalRows[1].header)
	assert.equal((await page.evaluate(() => window.headerRowTest.saves())).length, 1)
	await editSecond()
	await detail('items').getByRole('button', { name: '清空', exact: true }).click()
	await rowDialog.getByRole('button', { name: '取消', exact: true }).click()
	await rowDialog.waitFor({ state: 'detached' })
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.rows()), savedRows, 'Cancel must discard the draft')
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.events()), { detailEvents: 0, importEvents: 0 })
	await page.evaluate(() => window.headerRowTest.dispose())
	await page.goto(`${server.resolvedUrls.local[0]}__header-row-test?panel=1`)
	const panel = page.locator('.data-source-panel__detail')
	await panel.locator('.print-header-table').waitFor({ timeout: 60_000 })
	await page.waitForFunction(() => window.headerRowTest.fetches().length > 0)
	assert.equal(await panel.locator('.data-source-panel__record-selector').count(), 0)
	assert.equal(await panel.locator('.vxe-tabs-header--suffix').getByRole('button', { name: '添加明细', exact: true }).isVisible(), true)
	await panel.locator('.vxe-table--main-wrapper .vxe-body--row').filter({ hasText: 'B' }).first().getByText('B', { exact: true }).click()
	await panel.locator('.print-header-table__row--active').first().getByText('B', { exact: true }).waitFor()
	await page.waitForFunction(() => document.querySelector('.data-source-panel__detail-form [data-lc-field="items"] input')?.value === '202')
	const panelRows = await page.evaluate(() => window.headerRowTest.rows())
	await editSecond()
	await detail('items').getByRole('button', { name: '获取数据', exact: true }).click()
	await page.waitForFunction(() => document.querySelector('.print-header-row-dialog [data-lc-field="items"] input')?.value === '220')
	assert.equal(await panel.isVisible(), true, 'Draft fetch must not unmount the header table')
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.rows()), panelRows)
	await rowDialog.getByRole('button', { name: '保存', exact: true }).click()
	await rowDialog.waitFor({ state: 'detached' })
	const updatedPanelRows = await page.evaluate(() => window.headerRowTest.rows())
	assert.deepEqual(updatedPanelRows[0], panelRows[0])
	assert.equal(updatedPanelRows[1].items[0].amount, 220)
	await page.waitForFunction(() => document.querySelector('.data-source-panel__detail-form [data-lc-field="items"] input')?.value === '220')
	assert.deepEqual(await page.evaluate(() => window.headerRowTest.events()), { detailEvents: 0, importEvents: 0 })
	await page.evaluate(() => window.headerRowTest.dispose())
	assert.deepEqual(errors, [])
	console.log('Browser verified formulas, pagination, independent row drafts, header table selection, detail switching, and the add-detail tab action.')
} catch (error) {
	console.error(await page?.evaluate(() => ({ text: document.body.innerText.slice(0, 2000), controls: [...document.querySelectorAll('.lc-field')].map(field => ({label: field.querySelector('label')?.textContent, value: field.querySelector('input,select')?.value})), initialized: Boolean(window.formulaTest) })))
	throw error
} finally {
	await browser?.close()
	await server.close()
}
